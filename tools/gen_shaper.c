/* Generates dsp/bd909_shaper.h: the D10/D11 diode shaper transfer, solved once offline
 * with the same component values and bisection as bd909.c used at init. Keeping it
 * as a constant table makes the device init cheap and deterministic (boot safety).
 * Build: gcc -DBD909_RUNTIME_SHAPER -o gen tools/gen_shaper.c dsp/bd909.c -lm && ./gen > dsp/bd909_shaper.h */
#include <stdio.h>
#include "../dsp/bd909.h"
int main(void){
  static BD909 b; bd909_init(&b, 48000.f);
  printf("/* generated by tools/gen_shaper.c - do not edit */\n#ifndef BD909_SHAPER_H\n#define BD909_SHAPER_H\n");
  printf("static const float BD909_SHAPER[%d] = {\n", BD_SHAPER_N + 1);
  for (int i = 0; i <= BD_SHAPER_N; i++) printf("%s%.9gf,%s", i % 6 ? " " : "    ", b.shaper[i], i % 6 == 5 ? "\n" : "");
  printf("\n};\n#endif\n");
  return 0;
}
